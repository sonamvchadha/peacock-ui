// Builds src/tokens/peacock.css (CSS variables) and src/tokens/resolved.json
// from the token source files in /tokens. Run with: npm run tokens
//
// Three tiers:
//   primitives.json         raw values (teal-700 = #0f6468)
//   semantic.<theme>.json   purpose names that point at primitives, per theme
//   component.json          component parts that point at semantic tokens
//
// Style Dictionary does this at scale. This script keeps the same idea small
// enough to read in one sitting.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const read = (f) => JSON.parse(readFileSync(new URL(`../tokens/${f}`, import.meta.url)));

// Flatten nested { a: { b: { $value } } } into [['a.b', value], ...]
const flatten = (obj, path = []) =>
  Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object' && '$value' in v ? [[[...path, k].join('.'), v.$value]] : flatten(v, [...path, k]),
  );

// color.teal.700 -> --pk-teal-700, color.accent.default -> --pk-accent, space.4 -> --pk-space-4
const cssName = (path) => {
  let parts = path.split('.');
  if (parts[0] === 'color') parts = parts.slice(1);
  if (parts.at(-1) === 'default') parts = parts.slice(0, -1);
  return `--pk-${parts.join('-')}`;
};
const toCss = (value) =>
  typeof value === 'string' && value.startsWith('{') ? `var(${cssName(value.slice(1, -1))})` : value;

const primitives = flatten(read('primitives.json'));
const themes = ['light', 'dark', 'rebrand'];
const semantic = Object.fromEntries(themes.map((t) => [t, flatten(read(`semantic.${t}.json`))]));
const component = flatten(read('component.json'));

// Every reference must point at a token that exists.
const known = new Set([...primitives, ...semantic.light, ...component].map(([p]) => p));
for (const [path, value] of [...Object.values(semantic).flat(), ...component]) {
  if (typeof value === 'string' && value.startsWith('{') && !known.has(value.slice(1, -1))) {
    throw new Error(`${path} points at ${value}, which does not exist`);
  }
}

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([p, v]) => `  ${cssName(p)}: ${toCss(v)};`).join('\n')}\n}\n`;

const css = [
  '/* Generated by scripts/build-tokens.mjs. Do not edit by hand: change /tokens and run npm run tokens. */\n',
  block(':root', primitives),
  block(':root, [data-theme="light"]', semantic.light),
  block('[data-theme="dark"]', semantic.dark),
  '/* The rebrand source only lists what changes; the rest is filled in from light so the theme works anywhere. */\n',
  block('[data-theme="rebrand"]', [...new Map([...semantic.light, ...semantic.rebrand])]),
  '/* Component tokens are declared on every themed element so they re-resolve inside nested themes. */\n',
  block(':root, [data-theme]', component),
].join('\n');

// Resolved hex values per theme, for docs and the contrast check.
const resolve = (theme) => {
  const map = new Map([...primitives, ...semantic.light, ...semantic[theme], ...component]);
  const val = (p, depth = 0) => {
    const v = map.get(p);
    if (depth > 16) throw new Error(`Alias chain too deep at ${p}`);
    return typeof v === 'string' && v.startsWith('{') ? val(v.slice(1, -1), depth + 1) : v;
  };
  return Object.fromEntries([...map.keys()].map((p) => [cssName(p), val(p)]));
};
const resolved = Object.fromEntries(themes.map((t) => [t, resolve(t)]));

mkdirSync(new URL('../src/tokens/', import.meta.url), { recursive: true });
writeFileSync(new URL('../src/tokens/peacock.css', import.meta.url), css);
writeFileSync(new URL('../src/tokens/resolved.json', import.meta.url), JSON.stringify(resolved, null, 2) + '\n');
console.log(`Built ${primitives.length} primitives, ${semantic.light.length} semantic, ${component.length} component tokens for ${themes.length} themes.`);
